"""Render a Markdown summary from a Phase 0 results JSON (default: the latest full run)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def mb(b) -> str:
    return f"{b / 2**20:,.0f} MB" if b else "n/a"


def ms(d: dict, k: str = "p50") -> str:
    return f"{d[k]:,.0f}" if d.get("n") else "n/a"


def main() -> None:
    if len(sys.argv) > 1:
        path = Path(sys.argv[1])
    else:
        path = sorted(p for p in (HERE / "results").glob("phase0-*.json") if "quick" not in p.name)[-1]
    d = json.loads(path.read_text())
    m = d["meta"]
    L = [f"# Phase 0 benchmark summary", "",
         f"Generated by `benchmarks/phase0/summarize.py` from `{path.relative_to(HERE.parents[1])}`. "
         "All numbers come from that file; none were typed by hand.", "",
         "## Run metadata", "",
         f"- Date (UTC): {m['date_utc']}",
         f"- Git commit: {m['git_commit']} (dirty: {m['git_dirty']})",
         f"- Hardware: {m['hardware']['chip']}, {m['hardware']['ram_bytes'] / 2**30:.0f} GB RAM, "
         f"{m['hardware']['cpu_count']} cores; {m['os']}",
         f"- Native: whisper.cpp {m['native']['whisper.cpp']}, llama.cpp {m['native']['llama.cpp']} (Metal)",
         f"- Python {m['python']}; " + ", ".join(f"{k} {v}" for k, v in m["packages"].items()),
         f"- Settings: {json.dumps(m['settings'])}",
         f"- System available memory at start: {mb(m['system_memory_at_start']['available_bytes'])} "
         "(VS Code, a browser and Claude Code were running)",
         "- Models: " + "; ".join(f"`{x['dest']}` sha256 `{x['sha256'][:12]}…`" for x in m["models"]), "",
         "## Each model alone", "",
         "| Component | Model | Max RSS | Peak footprint | Load / ready (ms) | Speed (p50 / p95) |",
         "|---|---|---:|---:|---:|---|"]
    v = d["vad"]
    L.append(f"| VAD | Silero v6.2.3 ONNX (CPU, 1 thread) | {mb(v['memory']['max_rss_bytes'])} | "
             f"{mb(v['memory']['peak_footprint_bytes'])} | {v['load_ms']:.0f} | "
             f"{v['frame_infer_ms']['p50']:.3f} / {v['frame_infer_ms']['p95']:.3f} ms per {v['frame_ms']:.0f} ms frame |")
    t = d["tts"]
    L.append(f"| TTS | Piper libritts_r medium | {mb(t['memory']['max_rss_bytes'])} | "
             f"{mb(t['memory']['peak_footprint_bytes'])} | {t['load_ms']:.0f} | "
             f"first chunk {ms(t['first_chunk_ms'])} / {ms(t['first_chunk_ms'], 'p95')} ms; "
             f"RTF {t['rtf']['p50']:.3f} / {t['rtf']['p95']:.3f} |")
    for k in ("asr_base.en", "asr_small.en"):
        a = d[k]
        L.append(f"| ASR | whisper {a['model']} | {mb(a['memory']['max_rss_bytes'])} | "
                 f"{mb(a['memory']['peak_footprint_bytes'])} | {a['ready_ms']:.0f} | "
                 f"latency {ms(a['latency_ms'])} / {ms(a['latency_ms'], 'p95')} ms; "
                 f"RTF {a['rtf']['p50']:.3f} / {a['rtf']['p95']:.3f} |")
    g = d["llm"]
    L.append(f"| LLM | Qwen2.5-1.5B-Instruct Q4_K_M, ctx {m['settings']['llm_ctx']} | "
             f"{mb(g['memory']['max_rss_bytes'])} | {mb(g['memory']['peak_footprint_bytes'])} | "
             f"{g['ready_ms']:.0f} | TTFT {ms(g['ttft_ms'])} / {ms(g['ttft_ms'], 'p95')} ms; "
             f"gen {g['gen_tokens_per_s']['p50']:.1f} / {g['gen_tokens_per_s']['p95']:.1f} tok/s |")
    L += ["", "\"Load / ready\" for ASR and LLM is process start until the HTTP server answers. "
          "ASR latency is the full HTTP request (upload, decode, response) on a resident whisper-server.", "",
          "### ASR per clip (p50 latency, WER)", "",
          "WER is from one transcript per clip (decoding is deterministic at temperature 0). "
          "*Normalized* maps digits 0–12 and Dr./Mr./Mrs. to words. Clips `caller_*` are Piper speech "
          "(speaker 20, a different voice from the agent's), not human recordings.", "",
          "| Clip | Audio (s) | base.en ms | base.en WER (norm / raw) | small.en ms | small.en WER (norm / raw) |",
          "|---|---:|---:|---:|---:|---:|"]
    for clip, b in d["asr_base.en"]["by_clip"].items():
        s = d["asr_small.en"]["by_clip"][clip]
        L.append(f"| {clip} | {b['audio_s']:.1f} | {ms(b['latency_ms'])} | {b['wer']:.3f} / {b['wer_raw']:.3f} | "
                 f"{ms(s['latency_ms'])} | {s['wer']:.3f} / {s['wer_raw']:.3f} |")
    lb = g.get("llama_bench")
    if isinstance(lb, list):
        L += ["", "### llama-bench", "", "| Test | tok/s (avg ± sd) |", "|---|---:|"]
        for r in lb:
            name = f"pp{r['n_prompt']}" if r.get("n_prompt") else f"tg{r['n_gen']}"
            L.append(f"| {name} | {r['avg_ts']:.1f} ± {r['stddev_ts']:.1f} |")
    L += ["", "## All models loaded together", "",
          "llama-server + whisper-server + one Python process (Silero VAD + Piper), running the real "
          "VAD → ASR → LLM → TTS sequence on every clip for several rounds.", "",
          "| ASR model | LLM RSS | ASR RSS | VAD+TTS RSS | **Sum of max RSS** | Sum of peak footprint | "
          "Budget 2.5 GB | Min system available | Swap growth |",
          "|---|---:|---:|---:|---:|---:|---|---:|---:|"]
    for k in ("combined_base.en", "combined_small.en"):
        c = d[k]
        p = c["memory"]
        L.append(f"| {c['asr_model']} | {mb(p['llm']['max_rss_bytes'])} | {mb(p['asr']['max_rss_bytes'])} | "
                 f"{mb(p['python_vad_tts']['max_rss_bytes'])} | **{mb(c['sum_max_rss_bytes'])}** | "
                 f"{mb(c['sum_peak_footprint_bytes'])} | {'fits' if c['fits_budget'] else 'EXCEEDS'} | "
                 f"{mb(c['system']['min_available_bytes'])} | {c['system']['swap_used_delta_bytes'] / 2**20:+.0f} MB |")
    L += ["", "The sum of max RSS is a conservative upper bound: it counts the memory-mapped GGUF pages "
          "and counts shared system libraries once per process, and the per-process peaks may not occur at "
          "the same time. Peak footprint leaves out clean memory-mapped pages, so it understates the LLM's "
          "memory.", ""]
    out = HERE / "summary.md"
    out.write_text("\n".join(L))
    print(out.read_text())


if __name__ == "__main__":
    main()
